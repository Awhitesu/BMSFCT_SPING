/**
 * @brief I²C总线复位函数
 * @param hi2c: I²C句柄指针
 * @retval HAL状态
 */
HAL_StatusTypeDef I2C_Reset(I2C_HandleTypeDef *hi2c)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_TypeDef *SCL_Port, *SDA_Port;
    uint16_t SCL_Pin, SDA_Pin;

    if (hi2c->Instance == I2C1) {
        SCL_Port = GPIOB; SCL_Pin = GPIO_PIN_6;
        SDA_Port = GPIOB; SDA_Pin = GPIO_PIN_7;
    } else if (hi2c->Instance == I2C2) {
        SCL_Port = GPIOB; SCL_Pin = GPIO_PIN_10;
        SDA_Port = GPIOB; SDA_Pin = GPIO_PIN_11;
    } else if (hi2c->Instance == I2C3) {
        SCL_Port = GPIOA; SCL_Pin = GPIO_PIN_8;
        SDA_Port = GPIOC; SDA_Pin = GPIO_PIN_9;
    } else {
        return HAL_ERROR;
    }

    // 1. De-initialize I2C peripheral
    HAL_I2C_DeInit(hi2c);

    // 2. Configure SCL and SDA as GPIO Output Open-Drain
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_OD;
    GPIO_InitStruct.Pull = GPIO_PULLUP; // Use internal pull-up for recovery
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    
    GPIO_InitStruct.Pin = SCL_Pin;
    HAL_GPIO_Init(SCL_Port, &GPIO_InitStruct);

    GPIO_InitStruct.Pin = SDA_Pin;
    HAL_GPIO_Init(SDA_Port, &GPIO_InitStruct);

    // 3. Manually generate clock pulses on SCL if SDA is low
    HAL_GPIO_WritePin(SDA_Port, SDA_Pin, GPIO_PIN_SET); // Release SDA
    if (HAL_GPIO_ReadPin(SDA_Port, SDA_Pin) == GPIO_PIN_RESET) { // Check if slave is holding SDA low
        for (int i = 0; i < 9; i++) {
            HAL_GPIO_WritePin(SCL_Port, SCL_Pin, GPIO_PIN_RESET);
            HAL_Delay(1);
            HAL_GPIO_WritePin(SCL_Port, SCL_Pin, GPIO_PIN_SET);
            HAL_Delay(1);
            if (HAL_GPIO_ReadPin(SDA_Port, SDA_Pin) == GPIO_PIN_SET) {
                break; // Slave released SDA
            }
        }
    }

    // 4. Generate a STOP condition: SCL high, SDA low -> high
    HAL_GPIO_WritePin(SCL_Port, SCL_Pin, GPIO_PIN_SET);
    HAL_GPIO_WritePin(SDA_Port, SDA_Pin, GPIO_PIN_RESET);
    HAL_Delay(1);
    HAL_GPIO_WritePin(SDA_Port, SDA_Pin, GPIO_PIN_SET);
    HAL_Delay(1);

    // 5. Re-initialize the I2C peripheral
    return HAL_I2C_Init(hi2c);
}

